import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const artifactDir = new URL('../.impeccable/review/', import.meta.url);
await fs.mkdir(artifactDir, { recursive: true });
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true,deviceScaleFactor:1});
await page.route('**/scene-audit',r=>r.fulfill({contentType:'text/html',body:'<meta name="viewport" content="width=device-width, initial-scale=1"><style>body{margin:0}#yard{width:100vw;height:100vh}</style><div id="yard"></div>'}));
await page.goto('http://127.0.0.1:5184/scene-audit');
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const report = await page.evaluate(async()=>{
 const {YardScene}=await import('/src/scene.ts');const {createState,ENTITY_LIMITS}=await import('/src/simulation.ts');const scene=new YardScene(document.querySelector('#yard'));await scene.load(()=>{});
 const s=createState();s.phase='playing';s.upgrades.saw=5;s.scrap=12;
 s.enemies=Array.from({length:ENTITY_LIMITS.enemies},(_,i)=>({id:i+1,x:Math.cos(i*2.4)*(4+i%7),z:Math.sin(i*2.4)*(4+i%7),hp:10,hit:0,seed:i,type:['can','runner','brute'][i%3]}));
 s.pickups=Array.from({length:ENTITY_LIMITS.pickups},(_,i)=>({id:1000+i,x:Math.cos(i*2.4)*(2+i%9),z:Math.sin(i*2.4)*(2+i%9),kind:i%2?'xp':'scrap',born:0}));
 for(let i=0;i<5;i++)scene.render(s,.016);
 let previous=performance.now();const durations=[];
 await new Promise(resolve=>{function frame(){const now=performance.now();durations.push(now-previous);previous=now;s.time+=.016;scene.render(s,.016);if(durations.length<90)requestAnimationFrame(frame);else resolve()}requestAnimationFrame(frame)});
 const sorted=durations.slice(5).sort((a,b)=>a-b);window.audit={scene,s};
 const result = {diagnostics:scene.diagnostics(),calls:scene.renderer.info.render.calls,triangles:scene.renderer.info.render.triangles,frames:sorted.length,medianFrameMs:sorted[Math.floor(sorted.length/2)],p95FrameMs:sorted[Math.floor(sorted.length*.95)]};
 s.player.x=1000;s.player.z=-1000;scene.render(s,.016);
 result.offscreen = {renderedEnemies:scene.diagnostics().renderedEnemies,simulationEnemies:s.enemies.length};
 s.player.x=0;s.player.z=0;scene.render(s,.016);return result;
});
await page.screenshot({path:fileURLToPath(new URL('mobile-render-stress.png',artifactDir))});
report.errors=errors;report.note='Headless Chrome touch emulation on host hardware; this is not a physical phone benchmark.';
await fs.writeFile(new URL('mobile-render-audit.json',artifactDir),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));await browser.close();
if(errors.length || report.triangles>500000 || report.offscreen.renderedEnemies!==0 || report.offscreen.simulationEnemies!==140)process.exitCode=1;
